// Default theme, renamed so it does not collide with ui2's own Default set.
// See third_party/gpui-kit.
module ui2

// component_theme_builtin_json lists the bundled theme files in picker order.
fn component_theme_builtin_json() []string {
	return [component_theme_json_neutral, component_theme_json_aurora, component_theme_json_ayu,
		component_theme_json_catppuccin, component_theme_json_gruvbox, component_theme_json_solarized,
		component_theme_json_tokyo_night]
}

// component_theme_builtin_sets returns the sets bundled with ui2, parsed from
// their theme files: Neutral (GPUI Kit's default, shadcn's neutral palette),
// Aurora (light only, with gradient buttons and bars), Ayu, Catppuccin (Latte
// and Mocha), Gruvbox, Solarized and Tokyo Night (dark only). The Default set
// is not among them; a registry always has it.
pub fn component_theme_builtin_sets() []ComponentThemeSet {
	mut sets := []ComponentThemeSet{}
	for source in component_theme_builtin_json() {
		sets << component_theme_set_from_json(source) or { continue }
	}
	return sets
}

